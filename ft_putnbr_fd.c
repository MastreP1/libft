#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	if (n < 0)
	{
		write(fd, "-", 1);
		n = n * -1;
	}
	while (n > 9)
	{
		ft_putchar_fd((n % 10), fd);
		n = n / 10;
	}
	n = n + 48;
	write(1, &n, 1);
	return ;
}
