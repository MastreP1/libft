#include "libft.h"

int	ft_isascii(char *str)
{
	int	i;

	if (!str)
		return (0);
	i = 0;
	while (str[i] >= 0 && str[i] <= 127)
	{
		i++;
	}
	if (str[i] == '\0')
		return (1);
	return (0);
}
