#include "libft.h"

int	ft_isdigit(char *str)
{
	int	i;

	if (!str)
		return (NULL);
	i = 0;
	while (str[i] < 48 && str[i] > 57)
	{
		i++;
	}
	if (str[i] == '\0')
		return (1);
	return (0);
}
