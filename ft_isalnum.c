#include "libft.h"

int	ft_isalnum(char *str)
{
	int	i;

	if (!str)
		return (0);
	i = 0;
	while (str[i] >= 48 && str[i] <= 57 || str[i] >= 65 && str[i] <= 90
		|| str[i] >= 98 && str[i] <= 122)
	{
		i++;
	}
	if (str[i] == '\0')
		return (1);
	return (0);
}
