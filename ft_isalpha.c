#include "libft.h"

int	ft_isalpha(char *str)
{
	int	i;

	if (!str)
		return (0);
	i = 0;
	while (str[i] < 65 && str[i] > 90 || str[i] < 97 && str[i] > 122)
	{
		i++;
	}
	if (str[i] == '\0')
		return (1);
	return (0);
}
