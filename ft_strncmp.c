#include "libft.h"

int	ft_strncmp(char *s1, char *s2, int n)
{
	int i = 0;
	int diff = 0;
	while (s1[i] && s2[i] && n > 0)
	{
		if (s1[i] != s2[i])
		{
			diff = s1[i] - s2[i];
			break ;
		}
		i++;
		n--;
	}
	return (diff);
}
